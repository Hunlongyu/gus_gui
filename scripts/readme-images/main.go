// Command readme-images wraps the original screenshots in a consistent SVG
// presentation. Run from the repository root: go run ./scripts/readme-images
package main

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"image/png"
	"log"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

const (
	// The captures include an eight-pixel desktop margin around the window.
	captureMargin = 8
	padding       = 80
)

var frame = template.Must(template.New("showcase").Parse(`<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{{.Width}}" height="{{.Height}}" viewBox="0 0 {{.Width}} {{.Height}}" role="img" aria-labelledby="title">
  <!-- Generated by go run ./scripts/readme-images; source: ../{{.Name}} -->
  <title id="title">{{.Title}}</title>
  <defs>
    <clipPath id="window">
      <rect x="{{.Padding}}" y="{{.Padding}}" width="{{.WindowWidth}}" height="{{.WindowHeight}}" rx="16"/>
    </clipPath>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="120%" color-interpolation-filters="sRGB">
      <feDropShadow dx="0" dy="8" stdDeviation="10" flood-color="#26354a" flood-opacity="0.08"/>
    </filter>
  </defs>
  <rect width="{{.Width}}" height="{{.Height}}" rx="24" fill="#e4e9f0"/>
  <rect x="{{.Padding}}" y="{{.Padding}}" width="{{.WindowWidth}}" height="{{.WindowHeight}}" rx="16" fill="#fff" filter="url(#shadow)"/>
  <image x="{{.ImageOffset}}" y="{{.ImageOffset}}" width="{{.ImageWidth}}" height="{{.ImageHeight}}" clip-path="url(#window)" xlink:href="data:image/png;base64,{{.PNG}}"/>
</svg>
`))

func main() {
	if err := generate(); err != nil {
		log.Fatal(err)
	}
}

func generate() error {
	outDir := filepath.Join("assets", "images", "showcase")
	if err := os.MkdirAll(outDir, 0755); err != nil {
		return err
	}
	screens := []struct{ name, en, zh string }{
		{"panel", "gus Main Interface", "gus 主界面"},
		{"accounts", "gus Accounts", "gus 账号管理"},
		{"switch", "gus Identity Switch Menu", "gus 右键菜单切换身份"},
		{"settings", "gus Settings", "gus 设置页"},
	}
	for _, screen := range screens {
		for _, suffix := range []string{"", "-en"} {
			name := "gus-" + screen.name + suffix + ".png"
			data, err := os.ReadFile(filepath.Join("assets", "images", name))
			if err != nil {
				return err
			}
			config, err := png.DecodeConfig(bytes.NewReader(data))
			if err != nil {
				return fmt.Errorf("%s: %w", name, err)
			}
			ww, wh := config.Width-2*captureMargin, config.Height-2*captureMargin
			if ww <= 0 || wh <= 0 {
				return fmt.Errorf("%s: screenshot is smaller than its margin", name)
			}
			title := screen.zh
			if suffix == "-en" {
				title = screen.en
			}
			var output bytes.Buffer
			err = frame.Execute(&output, map[string]any{
				"Name": name, "Title": title,
				"Width": ww + 2*padding, "Height": wh + 2*padding,
				"Padding":     padding,
				"WindowWidth": ww, "WindowHeight": wh,
				"ImageWidth": config.Width, "ImageHeight": config.Height,
				"ImageOffset": padding - captureMargin,
				"PNG":         base64.StdEncoding.EncodeToString(data),
			})
			if err != nil {
				return err
			}
			path := filepath.Join(outDir, strings.TrimSuffix(name, ".png")+".svg")
			if err := os.WriteFile(path, output.Bytes(), 0644); err != nil {
				return err
			}
			fmt.Println(path)
		}
	}
	return nil
}
